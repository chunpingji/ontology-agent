  await button("清空选择").click();
  assert.equal(await button("生成批 GxP 草稿").isDisabled(), true);
  await select("研发类 CMC 文档", reportB);
  await dialog.getByRole("checkbox", { name: "01 投料", exact: true }).waitFor();
  assert.equal(await dialog.getByRole("checkbox", { checked: true }).count(), 8);
  await select("研发类 CMC 文档", reportA);
  await dialog.getByRole("checkbox", { name: "01 清场", exact: true }).waitFor();
  assert.equal(await dialog.getByRole("checkbox", { checked: true }).count(), 10);
  await dialog.getByRole("checkbox", { name: "01 清场", exact: true }).uncheck();
  await page.screenshot({ path: `${output}/generator-desktop.png`, fullPage: true, animations: "disabled" });
  await button("生成批 GxP 草稿").click();
  await page.getByRole("heading", { name: "批 GxP 配置 · DEMO-A-001", exact: true }).waitFor();
  const tree = page.getByRole("navigation", { name: "批工艺操作", exact: true });
