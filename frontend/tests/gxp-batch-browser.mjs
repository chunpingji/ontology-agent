  await tree.getByRole("button", { name: /自定义操作/ }).waitFor();
  await goBatch("DEMO-A-001", "A");
  assert.equal(await page.getByLabel("物料温度下限", { exact: true }).inputValue(), "96");

  await page.setViewportSize({ width: 390, height: 844 });
  await button("生成批号工艺").click();
  await page.screenshot({ path: `${output}/generator-mobile.png`, fullPage: true, animations: "disabled" });
